// Generates vo/voice.js (base64 PCM per line) with espeak-ng + MBROLA id1.
// Each line's speaking rate is raised until it fits its slot in the video.
// Env: ESPEAK (binary path), ESPEAK_DATA_PATH, PATH must contain mbrola.
const { execFileSync } = require('child_process');
const fs = require('fs'), path = require('path'), os = require('os');
const { VO_LINES } = require('./lines.js');
const ESPEAK = process.env.ESPEAK || 'espeak-ng', VOICE = process.env.VOICE || 'mb-id1';
const tmp = path.join(os.tmpdir(), `vo-${process.pid}.wav`);

function readWav(buf) {
  let o = 12, fmt, data;
  while (o < buf.length - 8) {
    const id = buf.toString('ascii', o, o + 4), sz = buf.readUInt32LE(o + 4);
    if (id === 'fmt ') fmt = { ch: buf.readUInt16LE(o + 10), sr: buf.readUInt32LE(o + 12), bits: buf.readUInt16LE(o + 22) };
    if (id === 'data') data = buf.subarray(o + 8, o + 8 + Math.min(sz, buf.length - o - 8));
    o += 8 + sz + (sz & 1);
  }
  if (!fmt || fmt.bits !== 16 || fmt.ch !== 1) throw new Error('unexpected wav format ' + JSON.stringify(fmt));
  return { sr: fmt.sr, pcm: new Int16Array(data.buffer.slice(data.byteOffset, data.byteOffset + (data.length & ~1))) };
}
function trim({ sr, pcm }) {
  const th = 250, pad = Math.round(sr * 0.02);
  let a = 0, b = pcm.length - 1;
  while (a < b && Math.abs(pcm[a]) < th) a++;
  while (b > a && Math.abs(pcm[b]) < th) b--;
  return { sr, pcm: pcm.slice(Math.max(0, a - pad), Math.min(pcm.length, b + pad)) };
}
function synth(text, rate) {
  execFileSync(ESPEAK, ['-v', VOICE, '-s', String(rate), '-w', tmp, text]);
  return trim(readWav(fs.readFileSync(tmp)));
}

const out = [];
VO_LINES.forEach((ln, i) => {
  const slot = (ln.t1 - ln.t0) * 0.97;
  let rate = 160, w = synth(ln.say, rate), dur = w.pcm.length / w.sr;
  for (let k = 0; k < 5 && dur > slot && rate < 240; k++) {
    rate = Math.min(240, Math.ceil(rate * (dur / slot) * 1.02));
    w = synth(ln.say, rate); dur = w.pcm.length / w.sr;
  }
  const fit = dur <= slot ? 'ok' : 'OVER';
  console.log(`${String(i).padStart(2)} ${ln.t0.toFixed(2)}-${ln.t1.toFixed(2)} slot ${slot.toFixed(2)}s  vo ${dur.toFixed(2)}s  rate ${rate}  ${fit}  | ${ln.say}`);
  out.push({ sr: w.sr, dur: +dur.toFixed(3), rate, b64: Buffer.from(w.pcm.buffer).toString('base64') });
});
fs.unlinkSync(tmp);
fs.writeFileSync(path.join(__dirname, 'voice.js'), `// generated by build-vo.js — espeak-ng + MBROLA id1\nwindow.VO_DATA = ${JSON.stringify(out)};\n`);
console.log('wrote vo/voice.js');
